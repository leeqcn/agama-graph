CAT_ORDER = {"法义": 0, "人物": 1, "地点": 2}


def sort_tags_by_rule_5_2(tag_list):
    """Order tags per AGENTS.md Rule 5.2: 法义 -> 人物 -> 地点 (preserving relative order within each group)."""
    return sorted(
        tag_list,
        key=lambda x: CAT_ORDER.get(MASTER_TAXONOMY.get(x, ("法义", ""))[0], 0),
    )


